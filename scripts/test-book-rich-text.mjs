// Pure structured-text and native-selection editor tests. No DOM internals,
// network/auth/database access, arbitrary HTML or browser editing commands.
import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import ts from "typescript";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
const require = createRequire(import.meta.url);
const compile = (path) => ts.transpileModule(fs.readFileSync(new URL(path, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const helpers = {};
vm.runInNewContext(compile("../src/lib/bookRichText.ts"), { exports: helpers });
const plain = helpers.bookRichFromText("Alfa beta\nGamma");
const bold = helpers.markBookRichSelection(plain, { start: 0, end: 4 }, "bold");
assert.equal(helpers.bookRichText(bold), "Alfa beta\nGamma");
assert.equal(bold.paragraphs[0].runs[0].bold, true);
const both = helpers.markBookRichSelection(bold, { start: 0, end: 4 }, "italic");
assert.equal(both.paragraphs[0].runs[0].italic, true);
const unbold = helpers.markBookRichSelection(both, { start: 0, end: 4 }, "bold");
assert.equal(Boolean(unbold.paragraphs[0].runs[0].bold), false);
assert.equal(unbold.paragraphs[0].runs[0].italic, true);
const centered = helpers.alignBookRichSelection(both, { start: 10, end: 10 }, "center");
assert.equal(centered.paragraphs[1].align, "center");
assert.equal(centered.paragraphs[0].align, undefined);
const typed = helpers.reconcileBookRichText(centered, "Alfa! beta\nGamma");
assert.equal(typed.paragraphs[0].runs[0].text, "Alfa!");
assert.equal(typed.paragraphs[0].runs[0].bold, true);
assert.equal(typed.paragraphs[1].align, "center");
const emptyLast = { version: 1, paragraphs: [{ runs: [{ text: "Testo" }] }, { align: "right", runs: [{ text: "" }] }] };
assert.equal(helpers.markBookRichSelection(emptyLast, { start: 0, end: 5 }, "bold").paragraphs[1].align, "right");
assert.equal(helpers.reconcileBookRichText(emptyLast, "Testo\nNuovo").paragraphs[1].align, "right");
assert.equal(helpers.reconcileBookRichText({ version: 1, paragraphs: [{ runs: [{ text: "a" }] }, { align: "right", runs: [{ text: "b" }] }] }, "a\n").paragraphs[1].align, "right", "deleting text retains its empty paragraph alignment");
for (const align of ["left", "center", "right", "justify"]) assert.equal(helpers.bookRichSelectionAlignment(helpers.alignBookRichSelection(plain, { start: 0, end: 14 }, align), { start: 0, end: 14 }), align);
for (const value of [{ version: 2, paragraphs: [] }, { version: 1, paragraphs: [{ runs: [{ text: "x", href: "javascript:x" }] }] }, { version: 1, paragraphs: [{ align: "<script>", runs: [{ text: "x" }] }] }, { version: 1, paragraphs: [{ runs: [{ text: "x".repeat(601) }] }] }]) assert.throws(() => helpers.validateBookRichDocument(value));
assert.equal(helpers.bookRichText(helpers.safeBookRichDocument(bold, "Altro corpo")), "Altro corpo");

const renderer = {};
vm.runInNewContext(compile("../src/components/books/BookRichText.tsx"), { exports: renderer, require: (id) => id === "react/jsx-runtime" ? require(id) : id.endsWith(".css") ? {} : helpers });
const html = renderToStaticMarkup(React.createElement(renderer.default, { body: "Alfa beta\nGamma", value: both }));
assert.match(html, /<strong><em>Alfa<\/em><\/strong>/);
assert.match(html, /text-align:justify;text-align-last:left/);
const dangerous = '<img src=x onerror="alert(1)">';
const safe = renderToStaticMarkup(React.createElement(renderer.default, { body: dangerous, value: helpers.bookRichFromText(dangerous) }));
assert.ok(!safe.includes("<img")); assert.match(safe, /&lt;img/);

let stateIndex = 0, refIndex = 0, props, changes = 0;
const states = [], refs = [], frames = [];
const hooks = { ...React, useState: (initial) => { const index = stateIndex++; if (!(index in states)) states[index] = initial; return [states[index], (next) => { states[index] = next; }]; }, useRef: (initial) => refs[refIndex++] ??= { current: initial }, useEffect: () => {} };
const editor = {};
vm.runInNewContext(compile("../src/components/books/BookRichTextEditor.tsx"), { exports: editor, window: { requestAnimationFrame: (fn) => { frames.push(fn); return frames.length; }, cancelAnimationFrame() {} }, require: (id) => id === "react" ? hooks : id === "react/jsx-runtime" ? require(id) : id.endsWith(".css") ? {} : id === "./BookRichText" ? renderer : helpers });
props = { body: "Alfa beta\nGamma", value: plain, label: "Commento", onChange: (body, value) => { changes++; props = { ...props, body, value }; } };
const render = () => { stateIndex = refIndex = 0; return editor.default(props); };
const find = (node, predicate) => { if (Array.isArray(node)) return node.flatMap((child) => find(child, predicate)); if (!node?.props) return []; return [...(predicate(node) ? [node] : []), ...find(node.props.children, predicate)]; };
let tree = render();
let focused = 0, restored;
refs[0].current = { selectionStart: 0, selectionEnd: 4, focus: () => focused++, setSelectionRange: (start, end) => { restored = [start, end]; } };
find(tree, (node) => node.type === "textarea")[0].props.onSelect(); tree = render();
const boldButton = find(tree, (node) => node.props["aria-label"] === "Grassetto selezione")[0];
let prevented = false; boldButton.props.onPointerDown({ preventDefault: () => { prevented = true; } }); boldButton.props.onClick();
assert.equal(prevented, true, "toolbar preserves native mobile selection");
assert.equal(props.value.paragraphs[0].runs[0].bold, true);
frames.splice(0).forEach((fn) => fn()); assert.equal(focused, 1); assert.deepEqual(restored, [0, 4]);
tree = render(); assert.equal(find(tree, (node) => node.props["aria-label"] === "Grassetto selezione")[0].props["aria-pressed"], true);
find(tree, (node) => node.props["aria-label"] === "Allineamento del paragrafo")[0].props.onChange({ target: { value: "right" } });
assert.equal(props.value.paragraphs[0].align, "right"); assert.ok(changes >= 2);
const focusCSS = fs.readFileSync(new URL("../src/components/books/BookCommentFocusView.css", import.meta.url), "utf8");
assert.match(focusCSS, /max-width:\s*min\(68ch, 760px\)/);
assert.match(focusCSS, /text-align-last:\s*left/);
assert.match(focusCSS, /book-comment-focus-title[^}]*text-align:center/);
assert.doesNotMatch(fs.readFileSync(new URL("../src/components/books/BookRichText.tsx", import.meta.url), "utf8"), /dangerouslySetInnerHTML/);
console.log("PASS: structured comment marks/alignment/edit reconciliation, legacy fallback, escaped rendering, native selection toolbar and readable justified focus layout (no writes).");
